import brandsData from "@/data/static/brands/brands.json";
import navData from "@/data/static/nav.json";
import { Brand, BrandGroup } from "@/types/brand";

/**
 * Generates a clean URL-friendly slug from a brand name
 * e.g., "Atlas Copco" -> "atlas-copco", "Allen-Bradley" -> "allen-bradley"
 */
export function slugifyBrand(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

interface RawBrand {
  name: string;
  count: number;
  group: string;
  categories: string[];
  description?: string;
}

// ---------------------------------------------------------------------------
// All brands come from brands.json (the single source of truth, generated by
// the legacy import script from curated + imported legacy parts).
// ---------------------------------------------------------------------------

const normalizedBrands: Brand[] = (brandsData as RawBrand[]).map((b) => ({
  name: b.name,
  slug: slugifyBrand(b.name),
  count: b.count,
  group: b.group,
  categories: [...b.categories],
  description: b.description,
}));

// Quick lookup maps
const brandSlugMap = new Map<string, Brand>();
const brandNameMap = new Map<string, Brand>();

for (const brand of normalizedBrands) {
  brandSlugMap.set(brand.slug.toLowerCase(), brand);
  brandNameMap.set(brand.name.toLowerCase(), brand);
}

/**
 * Build brand groups from brands.json, preserving nav.json group order and
 * descriptions.  Every brand in brands.json is assigned to the nav group
 * whose name matches its `group` field; brands with no matching nav group
 * fall into an "Other Brands" group at the end.
 */
function buildGroups(): BrandGroup[] {
  const brandByGroup = new Map<string, Brand[]>();
  for (const brand of normalizedBrands) {
    const list = brandByGroup.get(brand.group) || [];
    list.push(brand);
    brandByGroup.set(brand.group, list);
  }

  const groups: BrandGroup[] = [];

  for (const navGroup of navData.groups || []) {
    const groupBrands = (brandByGroup.get(navGroup.name) || []).sort(
      (a, b) => b.count - a.count || a.name.localeCompare(b.name)
    );
    if (groupBrands.length > 0) {
      groups.push({
        name: navGroup.name,
        description: navGroup.description,
        brands: groupBrands,
      });
    }
  }

  // Any brands not covered by a nav group (shouldn't happen, but be safe).
  const covered = new Set(groups.flatMap((g) => g.brands.map((b) => b.name)));
  const leftover = normalizedBrands.filter((b) => !covered.has(b.name));
  if (leftover.length > 0) {
    groups.push({
      name: "Other Brands",
      description: "Additional manufacturers supported by AGO Aviation.",
      brands: leftover.sort((a, b) => b.count - a.count || a.name.localeCompare(b.name)),
    });
  }

  return groups;
}

const normalizedGroups: BrandGroup[] = buildGroups();

/**
 * Returns all brands from brands.json, augmented with slug
 */
export function getAll(): Brand[] {
  return [...normalizedBrands];
}

/**
 * Retrieves a brand by its slug or name (case-insensitive)
 */
export function getBySlug(slug: string): Brand | undefined {
  if (!slug) return undefined;
  const clean = decodeURIComponent(slug).trim().toLowerCase().replace(/\.html$/i, "");
  const slugified = clean.replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

  return (
    brandSlugMap.get(clean) ||
    brandSlugMap.get(slugified) ||
    brandNameMap.get(clean) ||
    normalizedBrands.find(
      (b) =>
        b.slug === clean ||
        b.slug === slugified ||
        b.name.toLowerCase() === clean
    )
  );
}

/**
 * Retrieves a brand by its display name
 */
export function getByName(name: string): Brand | undefined {
  if (!name) return undefined;
  const clean = name.trim().toLowerCase();
  return (
    brandNameMap.get(clean) ||
    normalizedBrands.find((b) => b.name.toLowerCase() === clean)
  );
}

/**
 * Returns all brand groups.  Brands are sourced from brands.json (which
 * includes imported legacy parts) while group order and descriptions come
 * from nav.json.
 */
export function getGroups(): BrandGroup[] {
  return [...normalizedGroups];
}

/**
 * Returns all brand slugs for static route generation (generateStaticParams)
 */
export function getAllSlugs(): string[] {
  return normalizedBrands.map((b) => b.slug);
}

export const BrandService = {
  getAll,
  getBySlug,
  getByName,
  getGroups,
  getAllSlugs,
  slugifyBrand,
};

export default BrandService;
